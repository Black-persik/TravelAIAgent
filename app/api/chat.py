"""Chat endpoints: stream the agent's answer and load a conversation's history.

The answer is streamed with Server-Sent Events (SSE): the response stays open and the
server sends small events as the model generates text. Events:
- `token`: {"text": "..."}, a piece of the answer
- `done`:  {"thread_id": "..."}, the answer is complete
- `error`: {"message": "..."}, the run failed
"""

import logging
from collections.abc import AsyncIterable
from typing import Annotated, Literal
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Request, status
from fastapi.sse import EventSourceResponse, ServerSentEvent
from langchain_core.messages import AIMessageChunk, HumanMessage
from pydantic import BaseModel, Field

from app.api.auth import CurrentUser
from app.observability import tracing_config

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api", tags=["chat"])

# Only tokens from this node are sent to the user. Later stages add internal LLM calls
# (request parsing, critics) whose output must not leak into the chat.
USER_FACING_NODES = {"respond"}


class ChatRequest(BaseModel):
    thread_id: UUID  # generated by the client, one per conversation
    message: str = Field(min_length=1, max_length=4000)


class ChatMessage(BaseModel):
    role: Literal["user", "assistant"]
    content: str


class ThreadOut(BaseModel):
    thread_id: UUID
    messages: list[ChatMessage]


def enforce_chat_rate_limit(request: Request, user: CurrentUser) -> str:
    if not request.app.state.chat_limiter.allow(user):
        raise HTTPException(status.HTTP_429_TOO_MANY_REQUESTS, "Too many messages, slow down")
    return user


RateLimitedUser = Annotated[str, Depends(enforce_chat_rate_limit)]


@router.post("/chat", response_class=EventSourceResponse)
async def chat(
    body: ChatRequest,
    request: Request,
    user: RateLimitedUser,
) -> AsyncIterable[ServerSentEvent]:
    graph = request.app.state.graph
    thread_id = str(body.thread_id)
    config = {
        "configurable": {"thread_id": thread_id},
        **tracing_config(request.app.state.settings, session_id=thread_id, user_id=user),
    }
    try:
        async for chunk, metadata in graph.astream(
            {"messages": [HumanMessage(content=body.message)]}, config, stream_mode="messages"
        ):
            if (
                isinstance(chunk, AIMessageChunk)
                and metadata.get("langgraph_node") in USER_FACING_NODES
                and chunk.text
            ):
                yield ServerSentEvent(event="token", data={"text": str(chunk.text)})
    except Exception:
        logger.exception("Agent run failed for thread %s", thread_id)
        yield ServerSentEvent(
            event="error", data={"message": "The agent could not answer. Please try again."}
        )
        return
    yield ServerSentEvent(event="done", data={"thread_id": thread_id})


@router.get("/threads/{thread_id}")
async def get_thread(
    thread_id: UUID,
    request: Request,
    user: CurrentUser,
) -> ThreadOut:
    """Conversation history, so the UI can restore a chat after a page reload."""
    snapshot = await request.app.state.graph.aget_state(
        {"configurable": {"thread_id": str(thread_id)}}
    )
    messages = (snapshot.values or {}).get("messages", [])
    roles = {"human": "user", "ai": "assistant"}
    return ThreadOut(
        thread_id=thread_id,
        messages=[
            ChatMessage(role=roles[m.type], content=str(m.text))
            for m in messages
            if m.type in roles and m.text
        ],
    )
